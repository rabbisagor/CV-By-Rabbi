import React, { useState } from 'react';
import { AiService, AiRequest } from '../../services/ai';
import { X, Sparkles, Copy, Check, ArrowRight, Loader2, RefreshCw } from 'lucide-react';

interface Props {
  initialAction?: 'objective' | 'summary' | 'improve_bullet' | 'suggest_skills' | 'translate' | 'tailor';
  initialPrompt?: string;
  roleName?: string;
  docLanguage: 'en' | 'bn';
  onApplyText: (text: string) => void;
  onClose: () => void;
  isBn: boolean;
}

export const AiAssistantModal: React.FC<Props> = ({
  initialAction = 'summary',
  initialPrompt = '',
  roleName = '',
  docLanguage,
  onApplyText,
  onClose,
  isBn,
}) => {
  const [action, setAction] = useState<AiRequest['action']>(initialAction);
  const [role, setRole] = useState<string>(roleName);
  const [prompt, setPrompt] = useState<string>(initialPrompt);
  const [targetLang, setTargetLang] = useState<'en' | 'bn'>(docLanguage);
  const [result, setResult] = useState<string>('');
  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [copied, setCopied] = useState<boolean>(false);
  const [sourceNote, setSourceNote] = useState<string>('');

  const handleGenerate = async () => {
    setIsLoading(true);
    setResult('');
    setSourceNote('');

    try {
      const res = await AiService.generate({
        action,
        prompt: prompt || role || 'Professional in Bangladesh',
        role,
        language: targetLang,
      });

      setResult(res.result);
      if (res.source === 'gemini') {
        setSourceNote(isBn ? 'গুগল জেমিনাই (Gemini) দ্বারা উৎপন্ন' : 'Generated by Google Gemini AI');
      } else {
        setSourceNote(isBn ? 'বিশেষজ্ঞ প্রিসেট পরামর্শ' : 'Curated professional suggestion');
      }
    } catch (err: any) {
      console.error(err);
      setResult('Failed to generate text. Please try again.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(result);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleApply = () => {
    onApplyText(result);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-xs p-4 overflow-y-auto">
      <div className="bg-white rounded-2xl max-w-xl w-full shadow-2xl border border-slate-100 overflow-hidden my-6">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-slate-100 bg-linear-to-r from-indigo-50 to-purple-50">
          <div className="flex items-center gap-2">
            <div className="p-1.5 rounded-lg bg-indigo-600 text-white">
              <Sparkles className="w-4 h-4" />
            </div>
            <div>
              <h3 className="font-bold text-slate-800 text-sm">
                {isBn ? 'এআই রাইটিং অ্যাসিস্ট্যান্ট' : 'AI CV Writing Assistant'}
              </h3>
              <p className="text-[11px] text-slate-500">
                {isBn ? 'গুগল জেমিনাই (Gemini API) চালিত' : 'Powered by Google Gemini'}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-white"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Body */}
        <div className="p-6 space-y-4">
          {/* Action Selector */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 mb-1.5">
              {isBn ? 'কী লিখতে চান?' : 'What would you like to generate?'}
            </label>
            <div className="grid grid-cols-2 sm:grid-cols-3 gap-2">
              {[
                { id: 'summary', label: isBn ? 'প্রফেশনাল সামারি' : 'Executive Summary' },
                { id: 'objective', label: isBn ? 'ক্যারিয়ার অবজেক্টিভ' : 'Career Objective' },
                { id: 'improve_bullet', label: isBn ? 'বুলেট পয়েন্ট রিরাইট' : 'Enhance Bullet Point' },
                { id: 'suggest_skills', label: isBn ? 'দক্ষতার পরামর্শ' : 'Suggest In-Demand Skills' },
                { id: 'tailor', label: isBn ? 'সার্কুলার অনুযায়ী সাজান' : 'Tailor to Job Circular' },
                { id: 'translate', label: isBn ? 'অনুবাদ (Bn ⇄ En)' : 'Translate Text' },
              ].map((opt) => (
                <button
                  key={opt.id}
                  type="button"
                  onClick={() => setAction(opt.id as any)}
                  className={`p-2 rounded-lg text-xs font-medium text-left border transition-all ${
                    action === opt.id
                      ? 'border-indigo-600 bg-indigo-50 text-indigo-700 font-bold'
                      : 'border-slate-200 text-slate-600 hover:bg-slate-50'
                  }`}
                >
                  {opt.label}
                </button>
              ))}
            </div>
          </div>

          {/* Role / Job Title */}
          <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                {isBn ? 'আপনার পেশা বা পদবি' : 'Target Role / Profession'}
              </label>
              <input
                type="text"
                value={role}
                onChange={(e) => setRole(e.target.value)}
                placeholder={isBn ? 'উদা: এইচআর অফিসার / সফটওয়্যার ইঞ্জিনিয়ার' : 'e.g. Senior Software Engineer'}
                className="w-full px-3 py-1.5 text-xs border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
              />
            </div>

            <div>
              <label className="block text-xs font-semibold text-slate-700 mb-1">
                {isBn ? 'আউটপুট ভাষা' : 'Output Language'}
              </label>
              <select
                value={targetLang}
                onChange={(e) => setTargetLang(e.target.value as any)}
                className="w-full px-3 py-1.5 text-xs border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
              >
                <option value="en">English (Professional)</option>
                <option value="bn">বাংলা (প্রমিত ও ব্যাকরণসম্মত)</option>
              </select>
            </div>
          </div>

          {/* Context / Prompt */}
          <div>
            <label className="block text-xs font-semibold text-slate-700 mb-1">
              {isBn ? 'বিষয়বস্তুর বিবরণ বা বাক্য' : 'Context, Details or Draft Text'}
            </label>
            <textarea
              rows={3}
              value={prompt}
              onChange={(e) => setPrompt(e.target.value)}
              placeholder={
                isBn
                  ? 'আপনার মূল দায়িত্ব, অর্জন বা সার্কুলারের যে অংশ উন্নত করতে চান তা এখানে লিখুন...'
                  : 'Enter your rough bullet point, key tasks or job circular requirements...'
              }
              className="w-full px-3 py-2 text-xs border border-slate-300 rounded-lg focus:outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
            />
          </div>

          {/* Generate Button */}
          <button
            type="button"
            onClick={handleGenerate}
            disabled={isLoading}
            className="w-full py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold rounded-xl shadow-xs transition-colors flex items-center justify-center gap-2 disabled:opacity-50"
          >
            {isLoading ? (
              <>
                <Loader2 className="w-4 h-4 animate-spin" />
                <span>{isBn ? 'জেনারেট হচ্ছে...' : 'Generating with Gemini AI...'}</span>
              </>
            ) : (
              <>
                <Sparkles className="w-4 h-4" />
                <span>{isBn ? 'এআই দিয়ে কন্টেন্ট লিখুন' : 'Generate Professional Content'}</span>
              </>
            )}
          </button>

          {/* Result Area */}
          {result && (
            <div className="p-4 bg-slate-50 border border-slate-200 rounded-xl space-y-3">
              <div className="flex justify-between items-center">
                <span className="text-[11px] font-semibold text-indigo-700 flex items-center gap-1">
                  <Check className="w-3.5 h-3.5" />
                  <span>{sourceNote || 'Generated'}</span>
                </span>
                <button
                  type="button"
                  onClick={handleCopy}
                  className="inline-flex items-center gap-1 text-[11px] text-slate-600 hover:text-slate-900 font-medium"
                >
                  <Copy className="w-3 h-3" />
                  <span>{copied ? (isBn ? 'কপি হয়েছে!' : 'Copied!') : (isBn ? 'কপি' : 'Copy')}</span>
                </button>
              </div>

              <div className="p-3 bg-white border border-slate-200 rounded-lg text-xs text-slate-800 leading-relaxed max-h-48 overflow-y-auto whitespace-pre-wrap">
                {result}
              </div>

              <div className="flex justify-end gap-2 pt-1">
                <button
                  type="button"
                  onClick={handleApply}
                  className="inline-flex items-center gap-1.5 px-4 py-2 bg-emerald-600 hover:bg-emerald-700 text-white text-xs font-bold rounded-lg shadow-xs transition-colors"
                >
                  <span>{isBn ? 'সিভিতে প্রয়োগ করুন' : 'Insert into CV'}</span>
                  <ArrowRight className="w-3.5 h-3.5" />
                </button>
              </div>
            </div>
          )}
        </div>
      </div>
    </div>
  );
};
